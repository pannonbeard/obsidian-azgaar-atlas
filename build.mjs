import {readFileSync, writeFileSync, rmSync, readdirSync} from "node:fs";
const artwork={};
for(const set of readdirSync("assets/relief")){
  for(const file of readdirSync("assets/relief/"+set)){
    if(file.endsWith(".svg"))artwork[set+"/"+file.slice(0,-4)]=readFileSync("assets/relief/"+set+"/"+file,"utf8");
  }
}
const art="const ReliefArt="+JSON.stringify(artwork)+";\n";
const detail="const ReliefView=(()=>{const module={exports:{}};\n"+readFileSync("src/relief-view.js","utf8")+"\nreturn module.exports;})();\n";
writeFileSync("src/relief-art.js","module.exports="+JSON.stringify(artwork)+";\n");
const core = readFileSync("src/core.js", "utf8");
const viewer = readFileSync("src/viewer.js", "utf8");
const plugin = readFileSync("src/plugin.js", "utf8");
writeFileSync("main.js", "// Azgaar Atlas 0.5.0 — generated by npm run build\n" +
  "const Core = (() => { const module = {exports:{}};\n" + core + "\nreturn module.exports; })();\n" +
  "const Viewer = (() => { const module = {exports:{}};\n" + art + detail + viewer + "\nreturn module.exports; })();\n" + plugin);
const runtime = "(()=>{\nconst Core=(()=>{const module={exports:{}};\n" + core +
  "\nreturn module.exports;})();\nconst Viewer=(()=>{const module={exports:{}};\n" + art + detail + viewer +
  "\nreturn module.exports;})();\n" + readFileSync("src/quartz-runtime.js","utf8") + "\n})();";
// Quartz treats .inline.ts imports as executable source, rather than TS modules.
// This file exports a string, so it must use an ordinary module filename.
writeFileSync("quartz5/azgaarAtlas.runtime.ts", "export default " + JSON.stringify(runtime) + "\n");
rmSync("quartz5/azgaarAtlas.inline.ts",{force:true});
writeFileSync("quartz5/azgaarAtlasCore.ts", "// @ts-nocheck\nexport default (()=>{const module={exports:{}};\n"+core+"\nreturn module.exports;})() as any\n");
